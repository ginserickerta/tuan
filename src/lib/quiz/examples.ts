export type SubjectFamily =
  | "math"
  | "physics"
  | "chemistry"
  | "biology"
  | "language"
  | "social"
  | "aptitude";

/** Map a free-text subject name to a family for example selection. */
export function subjectFamily(subject: string): SubjectFamily {
  const s = subject.toLowerCase();
  if (/คณิต|math/.test(s)) return "math";
  if (/ฟิสิกส์|physics|tpat3/.test(s)) return "physics";
  if (/เคมี|chem/.test(s)) return "chemistry";
  if (/ชีว|bio|tpat1/.test(s)) return "biology";
  if (/ไทย|อังกฤษ|eng|ภาษา|tgat1/.test(s)) return "language";
  if (/สังคม|social/.test(s)) return "social";
  return "aptitude"; // TGAT2/3, TPAT อื่นๆ, ไม่รู้จัก
}

